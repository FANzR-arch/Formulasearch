// Local end-to-end contract. Requires site :4321 and public PersonalAI :5174.
import { chromium } from 'playwright'
import { expect } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdirSync, readFileSync } from 'node:fs'
import { personalAiUrl } from '../src/lib/personal-ai.mjs'
const base = process.env.PAI_TEST_BASE_URL || 'http://127.0.0.1:4321'
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_BROWSER_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' })
mkdirSync('output/playwright', {recursive:true})
let current
const input = page => page.frameLocator('.pai-surface iframe').getByRole('textbox', {name:/输入消息|Message input/})
const child = page => page.frames().find(f => f.url().includes(':5174/chat'))
const ready = async page => { await expect(page.locator('.pai-surface')).toHaveAttribute('data-ready',''); await expect(input(page)).toBeVisible() }
const state = (page,s) => expect(page.locator('html')).toHaveAttribute('data-ai-state',s)
const homeOpen = async page => {
  const avatar = page.locator('[data-ai-avatar]:visible')
  await avatar.locator('.home-avatar__frame').focus()
  await avatar.locator('[data-ai-open]').click()
  await state(page,'chat')
  await ready(page)
}
const snap = async (page,name) => page.screenshot({path:'output/playwright/personal-ai-'+name+'.png'})
try {
  for (const value of ['', 'http://example.com/chat', 'https://localhost/chat','https://127.0.0.1/chat','https://[::1]/chat','https://example.com/admin','https://user:pass@example.com/chat']) assert.equal(personalAiUrl(value),undefined)
  assert.equal(personalAiUrl('https://chat.example.com/chat'),'https://chat.example.com/chat')
  assert.ok(!/<div\b[^>]*data-personal-ai/.test(readFileSync('dist/index.html','utf8')), 'Production endpoint unset: no UI')
  for(const mobile of [false,true]) {
    const context = await browser.newContext({ viewport: mobile ? {width:390,height:844} : {width:1440,height:1000}, isMobile:mobile,hasTouch:mobile })
    const page = current = await context.newPage()
    const errors = []; page.on('pageerror',e=>errors.push(e.message))
    await page.goto(base+'/')
    await page.locator('#intro-overlay').waitFor({state:'hidden'})
    const avatar = page.locator('[data-ai-avatar]:visible')
    const portrait = avatar.locator('.home-avatar__frame')
    const bubble = avatar.locator('[data-ai-open]')
    await expect(page.locator('.pai-nav-trigger')).toBeHidden()
    if(mobile) {
      // A deterministic clock verifies the full two-hint lifecycle without a real 30s pause.
      await page.clock.install()
      await page.clock.runFor(5100)
      await expect(avatar).toHaveAttribute('data-hint','')
      await page.clock.runFor(2100)
      await expect(avatar).not.toHaveAttribute('data-hint','')
      await page.clock.runFor(20100)
      await expect(avatar).toHaveAttribute('data-hint','')
      await page.clock.runFor(3000)
      await expect(avatar).not.toHaveAttribute('data-hint','')
      await page.clock.resume()
      await portrait.tap()
    } else {
      await avatar.hover()
      await expect(bubble).toBeVisible()
      await bubble.hover()
      await expect(avatar.locator('.pai-invitation-label')).toHaveCSS('opacity','1')
      await portrait.click()
    }
    await state(page,'intro') // Portrait alone never opens the conversation.
    await expect(bubble).toBeVisible()
    await snap(page,(mobile?'mobile':'desktop')+'-invitation')
    await bubble.click()
    await state(page,'entering')
    await expect(page.locator('.pai-home iframe')).toHaveCSS('opacity','0')
    await state(page,'chat')
    await ready(page)
    await expect(page.locator('#main-content')).toHaveAttribute('inert','')
    await expect(page.locator('.intro > h1')).toHaveCSS('opacity','0')
    await expect(child(page).locator('html')).toHaveAttribute('data-portfolio','immersive')
    await expect(child(page).locator('body')).toHaveCSS('background-color','rgba(0, 0, 0, 0)')
    await expect(child(page).locator('.host-greeting p')).toContainText('你好')
    // Input usable before the greeting finishes; draft doesn't enter model history.
    await input(page).fill('保留这段未发送的草稿')
    await expect(child(page).locator('[data-testid=user-message]')).toHaveCount(0)
    for(const theme of ['dark','light']) {
      await page.evaluate(t=>document.documentElement.dataset.theme=t,theme)
      await expect(child(page).locator('html')).toHaveClass(theme==='dark'?'dark':'')
      await page.waitForTimeout(300)
      await snap(page,(mobile?'mobile':'desktop')+'-home-'+theme)
    }
    await page.evaluate(()=>document.documentElement.dataset.locale='en')
    await expect(input(page)).toHaveAttribute('placeholder','What would you like to know?')
    await page.evaluate(()=>document.documentElement.dataset.locale='zh')
    await expect(input(page)).toHaveAttribute('placeholder','想了解什么？')
    // Each invalid dimension independently rejected.
    await page.evaluate(()=>{
      const source=document.querySelector('.pai-surface iframe').contentWindow
      window.dispatchEvent(new MessageEvent('message',{origin:'https://invalid.example',source,data:{type:'pai:close'}}))
      window.dispatchEvent(new MessageEvent('message',{origin:'http://127.0.0.1:5174',source:window,data:{type:'pai:close'}}))
    })
    await child(page).evaluate(()=>parent.postMessage({type:'pai:navigate',path:'https://invalid.example'},'http://127.0.0.1:4321'))
    await state(page,'chat')
    const y=await page.evaluate(()=>scrollY)
    await page.mouse.move(10,400); await page.mouse.wheel(0,600)
    if(mobile) {
      const cdp=await context.newCDPSession(page)
      await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:8,y:600}]})
      await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:8,y:200}]})
      await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
      await cdp.detach()
    }
    assert.equal(await page.evaluate(()=>scrollY),y)
    await input(page).press('Escape')
    await state(page,'intro')
    await expect(bubble).toBeFocused()
    await expect(page.locator('#main-content')).not.toHaveAttribute('inert','')
    await expect(page.locator('.pai-strands')).toHaveAttribute('data-running','false')
    await bubble.click(); await state(page,'chat')
    await expect(input(page)).toHaveValue('保留这段未发送的草稿')
    await expect(child(page).locator('.host-greeting p')).toContainText('聊聊你的想法')
    // Same-document collapse lets an active response finish.
    await input(page).fill('你好，请介绍一下 Phil')
    await child(page).getByRole('button',{name:'发送消息',exact:true}).click()
    await expect(child(page).getByRole('button',{name:'停止生成',exact:true})).toBeVisible()
    await page.locator('.pai-close').click()
    await state(page,'intro')
    await page.waitForTimeout(2300)
    await bubble.click(); await state(page,'chat')
    await expect(child(page).getByRole('button',{name:'停止生成',exact:true})).toHaveCount(0)
    await expect(child(page).getByTestId('assistant-message')).toContainText('固定演示回答')
    await input(page).fill('切换页面后继续编辑')
    // Real recommended archive link asks the host to navigate.
    await child(page).getByRole('link',{name:'作品档案'}).click()
    await page.waitForURL(base+'/projects')
    await expect(page.locator('.pai-nav-trigger')).toBeVisible()
    await expect(page.locator('.pai-dialog')).not.toBeVisible()
    await page.locator('.pai-nav-trigger').click(); await ready(page)
    await expect(input(page)).toHaveValue('切换页面后继续编辑')
    await expect(child(page).getByTestId('user-message')).toHaveCount(1)
    await child(page).getByRole('button',{name:'历史',exact:true}).click()
    await expect(child(page).getByRole('dialog')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(child(page).getByRole('dialog')).toBeHidden()
    await expect(page.locator('.pai-dialog')).toBeVisible()
    // Partial stream persists as stopped across a navigation.
    await input(page).fill('你好，再介绍一下')
    await child(page).getByRole('button',{name:'发送消息',exact:true}).click()
    await expect(child(page).getByRole('button',{name:'停止生成',exact:true})).toBeVisible()
    // A valid host navigation message avoids clicking inert navigation behind an inner-page modal.
    await child(page).evaluate(()=>parent.postMessage({type:'pai:navigate',path:'/blog'},'http://127.0.0.1:4321'))
    await page.waitForURL(base+'/blog')
    assert.notEqual(await page.evaluate(()=>sessionStorage.getItem('pai-save-warning')),'1')
    await page.locator('.pai-nav-trigger').click(); await ready(page)
    await expect(child(page).getByTestId('user-message')).toHaveCount(2)
    await expect(child(page).getByRole('button',{name:'停止生成',exact:true})).toHaveCount(0)
    await expect(child(page).locator('.host-stopped')).toBeVisible()
    await snap(page,(mobile?'mobile':'desktop')+'-panel')
    await input(page).fill('刷新保存草稿')
    await page.reload()
    await page.locator('.pai-nav-trigger').click(); await ready(page)
    await expect(input(page)).toHaveValue('刷新保存草稿')
    await input(page).press('Escape')
    await expect(page.locator('.pai-dialog')).toBeHidden()
    await expect(page.locator('.pai-nav-trigger')).toBeFocused()
    await page.mouse.wheel(0,600); await page.waitForTimeout(450)
    assert.ok(await page.evaluate(()=>scrollY>0),'Scroll resumes')
    await page.goBack()
    await expect(page.locator('.pai-nav-trigger')).toBeVisible()
    assert.deepEqual(errors,[])
    console.log((mobile?'Mobile':'Desktop')+': invitation, transitions, greeting, themes, locale, input, focus, scroll, links, persistence and pause passed')
    await context.close()
  }
  const context=await browser.newContext({reducedMotion:'reduce'})
  const page=current=await context.newPage()
  await page.goto(base+'/'); await page.locator('#intro-overlay').waitFor({state:'hidden'})
  await homeOpen(page)
  await expect(child(page).locator('.host-greeting p')).toContainText('聊聊你的想法')
  await expect(page.locator('.pai-strands')).toHaveAttribute('data-running','false')
  await page.locator('.pai-close').click(); await state(page,'intro')
  await page.locator('[data-ai-avatar]:visible [data-ai-open]').click()
  await page.locator('.pai-close').click(); await state(page,'intro')
  await page.waitForTimeout(1100); await state(page,'intro')
  // WebGL context loss keeps the chat usable.
  await homeOpen(page)
  await page.locator('.pai-strands canvas').evaluate(c=>c.dispatchEvent(new Event('webglcontextlost',{cancelable:true})))
  await expect(page.locator('.pai-strands')).toHaveAttribute('data-fallback','true')
  await expect(input(page)).toBeVisible()
  await context.close()
  const failed=await browser.newContext()
  const offline=current=await failed.newPage()
  await offline.route('http://127.0.0.1:5174/**',r=>r.abort())
  await offline.goto(base+'/'); await offline.locator('#intro-overlay').waitFor({state:'hidden'})
  const a=offline.locator('[data-ai-avatar]:visible')
  await a.locator('.home-avatar__frame').focus()
  await a.locator('[data-ai-open]').click()
  await expect(offline.locator('.pai-retry')).toBeVisible({timeout:15000})
  await offline.unroute('http://127.0.0.1:5174/**')
  await offline.locator('.pai-retry').click(); await ready(offline)
  await failed.close()
  console.log('Reduced motion, cancellation, WebGL fallback, offline recovery and production gating passed')
} catch(e) { await current?.screenshot({path:'output/playwright/personal-ai-failure.png'}).catch(()=>{}); throw e }
finally { await browser.close() }


await import('./test-personal-ai-navigation.mjs')
